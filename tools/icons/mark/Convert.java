import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import javax.xml.parsers.DocumentBuilderFactory;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;

/**
 * Turns the mark's SVG masters into the Android vector drawables and the guide's
 * favicon (issue #177; docs/design.md §5).
 *
 * <p>Run it through {@code tools/icons/mark.sh}, never directly: the shell script
 * owns the source-to-output table and the labels. A single-file Java program so
 * the icon pipeline needs no dependency beyond the JDK that already runs the
 * build — the same reason {@code tools/icons/fetch.sh} needs only java for
 * Valkyrie.
 *
 * <p>Only the SVG subset the masters use is understood: {@code <rect>} (with an
 * optional {@code rx}), {@code <path>}, and a {@code <g clip-path="url(#…)">}
 * whose {@code clipPath} lives in {@code <defs>}. Anything else fails loudly
 * rather than being dropped.
 *
 * <pre>
 *   java Convert.java vector  &lt;in.svg&gt; &lt;out.xml&gt; &lt;widthDp&gt; &lt;heightDp&gt;
 *   java Convert.java favicon &lt;in.svg&gt; &lt;out.svg&gt; &lt;paper&gt;
 * </pre>
 */
public final class Convert {

    /** One drawing of a master: a path, or a clipped group of them. */
    private sealed interface Node permits Group, Shape {}

    /** A filled or stroked shape of a master, already on the master's grid. */
    private record Shape(String pathData, String fill, String stroke, String strokeWidth)
            implements Node {}

    /** A group cut to a clip path, which is how the letter's colour bands are drawn. */
    private record Group(String clip, String clipId, List<Node> children) implements Node {}

    /** The favicon's tile radius: 22 % of the 108-unit canvas (docs/design.md §4). */
    private static final String TILE_RADIUS = "24";

    public static void main(String[] args) throws Exception {
        if (args.length == 0) {
            System.err.println(
                    "usage: Convert.java vector <in.svg> <out.xml> <widthDp> <heightDp>\n"
                            + "       Convert.java favicon <in.svg> <out.svg> <paper>");
            System.exit(2);
            return;
        }
        switch (args[0]) {
            case "vector" -> {
                require(args, 5);
                vector(Paths.get(args[1]), Paths.get(args[2]), args[3], args[4]);
            }
            case "favicon" -> {
                require(args, 4);
                favicon(Paths.get(args[1]), Paths.get(args[2]), args[3]);
            }
            default -> throw new IllegalArgumentException("unknown mode: " + args[0]);
        }
    }

    private static void require(String[] args, int count) {
        if (args.length != count) {
            throw new IllegalArgumentException(
                    "expected " + (count - 1) + " arguments after the mode, got " + (args.length - 1));
        }
    }

    // --- Android vector drawable -------------------------------------------------

    private static void vector(Path in, Path out, String widthDp, String heightDp) throws Exception {
        Document svg = parse(in);
        String viewBox = attr(svg.getDocumentElement(), "viewBox");
        if (viewBox == null) {
            throw new IllegalStateException(in + " has no viewBox");
        }
        String[] box = viewBox.trim().split("[ ,]+");

        StringBuilder xml = new StringBuilder();
        xml.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
        xml.append("<!-- Generated by tools/icons/mark.sh from ")
                .append(in.getFileName())
                .append(". Do not edit. -->\n");
        xml.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
        xml.append("    android:width=\"").append(widthDp).append("\"\n");
        xml.append("    android:height=\"").append(heightDp).append("\"\n");
        xml.append("    android:viewportWidth=\"").append(box[2]).append("\"\n");
        xml.append("    android:viewportHeight=\"").append(box[3]).append("\">\n");
        appendVector(xml, nodes(svg), 4);
        xml.append("</vector>\n");

        write(out, xml.toString());
    }

    private static void appendVector(StringBuilder xml, List<Node> nodes, int indent) {
        for (Node node : nodes) {
            switch (node) {
                case Group group -> {
                    xml.append(pad(indent)).append("<group>\n");
                    xml.append(pad(indent + 4))
                            .append("<clip-path\n")
                            .append(pad(indent + 8))
                            .append("android:pathData=\"")
                            .append(group.clip())
                            .append("\" />\n");
                    appendVector(xml, group.children(), indent + 4);
                    xml.append(pad(indent)).append("</group>\n");
                }
                case Shape shape -> {
                    xml.append(pad(indent)).append("<path\n");
                    xml.append(pad(indent + 4))
                            .append("android:pathData=\"")
                            .append(shape.pathData())
                            .append('"');
                    if (shape.fill() != null) {
                        xml.append("\n")
                                .append(pad(indent + 4))
                                .append("android:fillColor=\"")
                                .append(shape.fill())
                                .append('"');
                    }
                    if (shape.stroke() != null) {
                        xml.append("\n")
                                .append(pad(indent + 4))
                                .append("android:strokeColor=\"")
                                .append(shape.stroke())
                                .append('"');
                        xml.append("\n")
                                .append(pad(indent + 4))
                                .append("android:strokeWidth=\"")
                                .append(shape.strokeWidth())
                                .append('"');
                    }
                    xml.append(" />\n");
                }
            }
        }
    }

    // --- The guide's favicon -----------------------------------------------------

    /**
     * The favicon is the mark on the paper tile, at the same 108-unit grid, so a
     * browser tab shows the same letter the launcher does.
     */
    private static void favicon(Path in, Path out, String paper) throws Exception {
        Document svg = parse(in);

        StringBuilder text = new StringBuilder();
        text.append("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 108 108\"")
                .append(" role=\"img\" aria-label=\"Lekto\">\n");
        text.append("  <!-- Generated by tools/icons/mark.sh from ")
                .append(in.getFileName())
                .append(". Do not edit. -->\n");
        text.append("  <rect width=\"108\" height=\"108\" rx=\"")
                .append(TILE_RADIUS)
                .append("\" fill=\"")
                .append(paper)
                .append("\"/>\n");
        StringBuilder clips = new StringBuilder();
        appendClipDefs(clips, nodes(svg), 4);
        if (clips.length() > 0) {
            text.append("  <defs>\n").append(clips).append("  </defs>\n");
        }
        appendSvg(text, nodes(svg), 2);
        text.append("</svg>\n");

        write(out, text.toString());
    }

    /** The clip paths a favicon needs, so its groups are cut like the drawable's. */
    private static void appendClipDefs(StringBuilder text, List<Node> nodes, int indent) {
        for (Node node : nodes) {
            if (node instanceof Group group) {
                text.append(pad(indent))
                        .append("<clipPath id=\"")
                        .append(group.clipId())
                        .append("\"><path d=\"")
                        .append(group.clip())
                        .append("\"/></clipPath>\n");
                appendClipDefs(text, group.children(), indent);
            }
        }
    }

    private static void appendSvg(StringBuilder text, List<Node> nodes, int indent) {
        for (Node node : nodes) {
            switch (node) {
                case Group group -> {
                    text.append(pad(indent))
                            .append("<g clip-path=\"url(#")
                            .append(group.clipId())
                            .append(")\">\n");
                    appendSvg(text, group.children(), indent + 2);
                    text.append(pad(indent)).append("</g>\n");
                }
                case Shape shape -> {
                    text.append(pad(indent)).append("<path d=\"").append(shape.pathData()).append('"');
                    if (shape.fill() != null) {
                        text.append(" fill=\"").append(shape.fill()).append('"');
                    }
                    if (shape.stroke() != null) {
                        text.append(" stroke=\"")
                                .append(shape.stroke())
                                .append("\" stroke-width=\"")
                                .append(shape.strokeWidth())
                                .append('"');
                    }
                    text.append("/>\n");
                }
            }
        }
    }

    // --- Parsing -----------------------------------------------------------------

    private static Document parse(Path file) throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        // The masters are ours and carry no DTD; refuse one rather than fetch it.
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        return factory.newDocumentBuilder().parse(file.toFile());
    }

    private static List<Node> nodes(Document svg) {
        Map<String, String> clips = new HashMap<>();
        NodeList clipPaths = svg.getElementsByTagName("clipPath");
        for (int i = 0; i < clipPaths.getLength(); i++) {
            Element clip = (Element) clipPaths.item(i);
            String id = attr(clip, "id");
            if (id == null) {
                throw new IllegalStateException("<clipPath> without an id");
            }
            clips.put(id, firstPath(clip, id));
        }
        return children(svg.getDocumentElement(), clips);
    }

    private static String firstPath(Element clip, String id) {
        NodeList paths = clip.getElementsByTagName("path");
        if (paths.getLength() != 1) {
            throw new IllegalStateException(
                    "clipPath #" + id + " must hold exactly one <path>, found " + paths.getLength());
        }
        return normalise(attr((Element) paths.item(0), "d"));
    }

    private static List<Node> children(Element parent, Map<String, String> clips) {
        List<Node> nodes = new ArrayList<>();
        NodeList children = parent.getChildNodes();
        for (int i = 0; i < children.getLength(); i++) {
            if (!(children.item(i) instanceof Element element)) {
                continue;
            }
            switch (element.getTagName()) {
                case "defs" -> { }
                case "g" -> {
                    String reference = attr(element, "clip-path");
                    if (reference == null || !reference.startsWith("url(#") || !reference.endsWith(")")) {
                        throw new IllegalStateException("<g> must carry clip-path=\"url(#…)\"");
                    }
                    String id = reference.substring("url(#".length(), reference.length() - 1);
                    String clip = clips.get(id);
                    if (clip == null) {
                        throw new IllegalStateException("no clipPath #" + id);
                    }
                    nodes.add(new Group(clip, id, children(element, clips)));
                }
                case "rect" -> nodes.add(rect(element));
                case "path" -> nodes.add(path(element));
                default -> throw new IllegalStateException(
                        "unsupported element <" + element.getTagName() + "> in a mark master");
            }
        }
        return nodes;
    }

    private static Shape path(Element element) {
        String d = attr(element, "d");
        if (d == null) {
            throw new IllegalStateException("<path> without d");
        }
        return new Shape(normalise(d), fill(element), stroke(element), strokeWidth(element));
    }

    private static Shape rect(Element element) {
        double x = number(element, "x", 0);
        double y = number(element, "y", 0);
        double w = number(element, "width", 0);
        double h = number(element, "height", 0);
        double rx = number(element, "rx", 0);
        return new Shape(rectPath(x, y, w, h, rx), fill(element), stroke(element), strokeWidth(element));
    }

    private static String rectPath(double x, double y, double w, double h, double rx) {
        if (rx <= 0) {
            return "M" + n(x) + "," + n(y) + "h" + n(w) + "v" + n(h) + "h" + n(-w) + "Z";
        }
        double r = Math.min(rx, Math.min(w, h) / 2);
        return "M" + n(x + r) + "," + n(y)
                + "H" + n(x + w - r)
                + "A" + n(r) + "," + n(r) + " 0 0 1 " + n(x + w) + "," + n(y + r)
                + "V" + n(y + h - r)
                + "A" + n(r) + "," + n(r) + " 0 0 1 " + n(x + w - r) + "," + n(y + h)
                + "H" + n(x + r)
                + "A" + n(r) + "," + n(r) + " 0 0 1 " + n(x) + "," + n(y + h - r)
                + "V" + n(y + r)
                + "A" + n(r) + "," + n(r) + " 0 0 1 " + n(x + r) + "," + n(y)
                + "Z";
    }

    private static String fill(Element element) {
        String fill = attr(element, "fill");
        if (fill == null) {
            return "#000000";
        }
        return "none".equals(fill) ? null : fill;
    }

    private static String stroke(Element element) {
        String stroke = attr(element, "stroke");
        return stroke == null || "none".equals(stroke) ? null : stroke;
    }

    private static String strokeWidth(Element element) {
        String width = attr(element, "stroke-width");
        return width == null ? "1" : width;
    }

    private static double number(Element element, String name, double fallback) {
        String value = attr(element, name);
        return value == null ? fallback : Double.parseDouble(value);
    }

    private static String attr(Element element, String name) {
        return element.hasAttribute(name) ? element.getAttribute(name) : null;
    }

    // --- Writing -----------------------------------------------------------------

    private static String pad(int indent) {
        return " ".repeat(indent);
    }

    private static String normalise(String pathData) {
        return pathData.trim().replaceAll("\\s+", " ");
    }

    private static String n(double value) {
        if (Math.abs(value - Math.rint(value)) < 0.0005) {
            return Long.toString(Math.round(value));
        }
        String text = String.format(Locale.ROOT, "%.3f", value);
        while (text.endsWith("0")) {
            text = text.substring(0, text.length() - 1);
        }
        return text.endsWith(".") ? text.substring(0, text.length() - 1) : text;
    }

    private static void write(Path out, String content) throws IOException {
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, content, StandardCharsets.UTF_8);
        System.out.println("  wrote " + out);
    }
}
