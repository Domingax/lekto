@file:Suppress("MagicNumber") // The ICO and ICNS headers are fixed-field binary formats;
// their field values are the formats', not choices of ours, and spelling each one as a constant
// would hide the layout instead of explaining it.

package app.lekto.tools

import org.jetbrains.skia.Canvas
import org.jetbrains.skia.EncodedImageFormat
import org.jetbrains.skia.Paint
import org.jetbrains.skia.PaintMode
import org.jetbrains.skia.Path
import org.jetbrains.skia.RRect
import org.jetbrains.skia.Surface
import org.w3c.dom.Element
import java.io.File
