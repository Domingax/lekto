import java.nio.ByteOrder
import javax.xml.parsers.DocumentBuilderFactory

/**
 * Renders the committed desktop icon rasters from the Android vector drawables
 * (issue #177; docs/design.md §5).
 *
 * The mark has one source of truth, the SVGs in `tools/icons/mark/`, which
 * `tools/icons/mark.sh` turns into the drawables this program reads. It is
 * deliberately not a second geometry: the rasters are the same paths, and the
 * only thing added here is the tile the launcher's mask would draw.
 *
 * The rasters are `app-icon.png` for the Linux package and the window icon,
 * `app-icon.ico` for Windows and `app-icon.icns` for macOS. Sizes below 48 px
 * carry the one-ink letter instead of the mark: at 16 px four colour bands are a
 * smudge, which is the same rule as the monochrome layer (docs/design.md §5).
 *
 * Run it with `./gradlew :app:renderAppIcon` from the repository root, or through
 * `tools/icons/mark.sh`. Skia is already on the desktop classpath through
 * Compose, so this needs no dependency of its own. The output is committed and
 * is not compared in CI: a raster is regenerated by hand, and the golden lane
 * records the vectors instead (`AppIconTest`).
 */
fun main() {
    renderInto(File("src/desktopMain/resources/app-icon"))
}

/**
 * Writes the three desktop rasters into [output]: the window icon's PNG, the
 * Windows ICO and the macOS ICNS. `main` points it at the committed resource
 * directory; `RenderAppIconTest` points it at a temporary one.
 */
internal fun renderInto(output: File) {
    output.mkdirs()
    writePng(File(output, "app-icon.png"), markPng(WINDOW_ICON, MarkLayer.MARK))
    writeIco(
        File(output, "app-icon.ico"),
        listOf(16 to MarkLayer.LETTER, 32 to MarkLayer.LETTER, 48 to MarkLayer.MARK, 256 to MarkLayer.MARK),
    )
    writeIcns(
        File(output, "app-icon.icns"),
        listOf(
            16 to MarkLayer.LETTER,
            32 to MarkLayer.LETTER,
            64 to MarkLayer.MARK,
            128 to MarkLayer.MARK,
            256 to MarkLayer.MARK,
            512 to MarkLayer.MARK,
            1024 to MarkLayer.MARK,
        ),
    )
    println("Rendered the desktop icon into ${output.path}")
}

/** A layer of the adaptive icon, as `tools/icons/mark.sh` wrote it. */
internal enum class MarkLayer(val file: String) {
    /** The letter carrying the mastery ramp: the launcher mark. */
    MARK("src/androidMain/res/drawable/ic_launcher_foreground.xml"),

    /** The letter alone: Android 13 tints it, and the desktop uses it below 48 px. */
    LETTER("src/androidMain/res/drawable/ic_launcher_monochrome.xml"),
}

/**
 * The mark at [size] pixels: the paper tile at the mark's 22 % radius, then the
 * shapes of the layer's 108-unit canvas, cropped to the 72 units a launcher's mask
 * shows. Rendering the crop is what keeps the mark the size the launcher draws it.
 *
 * [background] paints the tile and [tint] replaces every colour of the layer,
 * which is how a themed icon renders the monochrome layer. `AppIconTest` calls
 * this so the golden records the same drawing the rasters are made from.
 */
internal fun markPng(size: Int, layer: MarkLayer, background: Long = PAPER, tint: Long? = null): ByteArray {
    val shapes = shapes(File(layer.file))
    val surface = Surface.makeRasterN32Premul(size, size)
    val canvas = surface.canvas
    canvas.clear(0)
    canvas.drawRRect(
        RRect.makeXYWH(0f, 0f, size.toFloat(), size.toFloat(), size * TILE_RADIUS),
        Paint().apply {
            isAntiAlias = true
            color = background.toInt()
        },
    )
    canvas.save()
    canvas.scale(size / VISIBLE_UNITS, size / VISIBLE_UNITS)
    canvas.translate(-BLEED_UNITS, -BLEED_UNITS)
    shapes.forEach { shape -> shape.draw(canvas, tint) }
    canvas.restore()
    val image = checkNotNull(surface.makeImageSnapshot().encodeToData(EncodedImageFormat.PNG)) {
        "Skia refused to encode the mark at $size px"
    }
    return image.bytes
}

/** One path of a generated drawable, with the paint its attributes name. */
private class Shape(val path: Path, val fill: Long?, val stroke: Long?, val strokeWidth: Float, val clip: Path?) {
    fun draw(canvas: Canvas, tint: Long?) {
        if (clip != null) {
            canvas.save()
            canvas.clipPath(clip)
        }
        fill?.let { colour -> canvas.drawPath(path, paint(colour, tint)) }
        stroke?.let { colour ->
            val stroked = paint(colour, tint)
            stroked.mode = PaintMode.STROKE
            stroked.strokeWidth = strokeWidth
            canvas.drawPath(path, stroked)
        }
        if (clip != null) {
            canvas.restore()
        }
    }

    private fun paint(colour: Long, tint: Long?): Paint = Paint().apply {
        isAntiAlias = true
        color = (tint ?: colour).toInt()
    }
}

private fun shapes(file: File): List<Shape> {
    check(file.isFile) { "missing ${file.path}: run tools/icons/mark.sh first" }
    val factory = DocumentBuilderFactory.newInstance()
    factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true)
    val root = factory.newDocumentBuilder().parse(file).documentElement
    val shapes = mutableListOf<Shape>()
    children(root).forEach { element ->
        when (element.tagName) {
            // The colour bands are cut to the letter, which is one clip per group.
            "group" -> {
                val clip = children(element)
                    .firstOrNull { it.tagName == "clip-path" }
                    ?.getAttribute("android:pathData")
                    ?.let(Path::makeFromSVGString)
                children(element)
                    .filter { it.tagName == "path" }
                    .forEach { shapes += shape(it, clip) }
            }

            "path" -> shapes += shape(element, null)

            else -> error("unsupported <${element.tagName}> in ${file.name}")
        }
    }
    return shapes
}

private fun shape(element: Element, clip: Path?): Shape = Shape(
    path = Path.makeFromSVGString(element.getAttribute("android:pathData")),
    fill = element.getAttribute("android:fillColor").takeIf(String::isNotEmpty)?.argb(),
    stroke = element.getAttribute("android:strokeColor").takeIf(String::isNotEmpty)?.argb(),
    strokeWidth = element.getAttribute("android:strokeWidth").takeIf(String::isNotEmpty)?.toFloat() ?: 1f,
    clip = clip,
)

private fun children(element: Element): List<Element> {
    val nodes = element.childNodes
    return (0 until nodes.length).mapNotNull { nodes.item(it) as? Element }
}

/** `#RRGGBB` to a Skia colour, opaque. */
private fun String.argb(): Long = 0xFF000000L or removePrefix("#").toLong(16)

internal fun writePng(file: File, png: ByteArray) {
    file.writeBytes(png)
    println("  wrote ${file.path}")
}

/**
 * A Windows icon: one directory, then the PNG payload of every frame. Windows
 * Vista and later read PNG payloads, so no bitmap re-encoding is needed.
 */
internal fun writeIco(file: File, frames: List<Pair<Int, MarkLayer>>) {
    val images = frames.map { (size, layer) -> size to markPng(size, layer) }
    val header = 6 + images.size * 16
    val buffer = ByteBuffer.allocate(header + images.sumOf { it.second.size }).order(ByteOrder.LITTLE_ENDIAN)
    buffer.putShort(0).putShort(1).putShort(images.size.toShort())
    var offset = header
    images.forEach { (size, png) ->
        buffer.put(size.toByte()).put(size.toByte()).put(0).put(0)
        buffer.putShort(1).putShort(32)
        buffer.putInt(png.size).putInt(offset)
        offset += png.size
    }
    images.forEach { (_, png) -> buffer.put(png) }
    file.writeBytes(buffer.array())
    println("  wrote ${file.path}")
}

/**
 * A macOS icon: a container of four-byte type codes, each followed by its PNG.
 * The codes are Apple's, one per pixel size.
 */
internal fun writeIcns(file: File, frames: List<Pair<Int, MarkLayer>>) {
    val entries = frames.map { (size, layer) -> ICNS_TYPES.getValue(size) to markPng(size, layer) }
    val total = 8 + entries.sumOf { 8 + it.second.size }
    val buffer = ByteBuffer.allocate(total).order(ByteOrder.BIG_ENDIAN)
    buffer.put("icns".toByteArray(Charsets.US_ASCII)).putInt(total)
    entries.forEach { (type, png) ->
        buffer.put(type.toByteArray(Charsets.US_ASCII)).putInt(8 + png.size).put(png)
    }
    file.writeBytes(buffer.array())
    println("  wrote ${file.path}")
}

// The mark's ground, docs/design.md §2.1, in ARGB.
private const val PAPER: Long = 0xFFFAF7F2

// The 108-unit canvas keeps 18 units of bleed on each side; 72 units are visible.
private const val VISIBLE_UNITS: Float = 72f
private const val BLEED_UNITS: Float = 18f

// 22 % of the tile (docs/design.md §4).
private const val TILE_RADIUS: Float = 0.22f

// The window icon and the Linux package icon: 512 is what a desktop dock asks for.
private const val WINDOW_ICON: Int = 512

/** Apple's type codes for the sizes the `.icns` carries. */
private val ICNS_TYPES: Map<Int, String> = mapOf(
    16 to "icp4",
    32 to "icp5",
    64 to "icp6",
    128 to "ic07",
    256 to "ic08",
    512 to "ic09",
    1024 to "ic10",
)
